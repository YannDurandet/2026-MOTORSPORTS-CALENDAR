#!/usr/bin/env node
/**
 * gen-track-map-status.mjs — Regenerates track-map-status.md from disk.
 *
 * The doc is an inventory of public/assets/track-maps/ cross-referenced against
 * data/tracks.json. It was hand-maintained and drifted badly: the summary table
 * disagreed with its own lists, two entries pointed at files that no longer
 * existed, and one file on disk was never listed. Generating it removes the
 * possibility.
 *
 * Two things are carried over from the existing file rather than derived, since
 * they are human knowledge the filesystem doesn't have:
 *   • the "Naming Convention" section
 *   • per-file annotations — the "— Indy Circuit" style suffixes
 * Add a new annotation by editing track-map-status.md, then re-running this;
 * it will survive.
 *
 * Usage: npm run gen:map-status
 *        npm run gen:map-status -- --check   (verify only, exit 1 if stale)
 */

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SVG_DIR    = resolve(__dirname, '../public/assets/track-maps');
const TRACKS     = resolve(__dirname, '../data/tracks.json');
const OUT_PATH   = resolve(__dirname, '../track-map-status.md');

const CHECK_ONLY = process.argv.includes('--check');

const FALLBACK_NAMING = [
  '## Naming Convention',
  '- `{venue}.svg` — generic / single-series',
  '- `{venue}-motogp.svg` — MotoGP uses different circuit config',
  '- `{venue}-fe.svg` — Formula E street overlay',
  '- `{venue}-wsbk.svg` — WSBK uses different circuit config',
  '- `{venue}-oval.svg` — superspeedway oval layout',
  '- `{venue}-road.svg` — road course at an oval venue',
  '- `{venue}-f1.svg` — F1-specific only when MotoGP also uses same venue',
  '- `{location}-wrc.svg` — all WRC / ERC national flags',
].join('\n');

// ── Inputs ───────────────────────────────────────────────────────────────────

const tracks = JSON.parse(readFileSync(TRACKS, 'utf8'));
const disk = readdirSync(SVG_DIR).filter(f => f.endsWith('.svg')).sort();

const prev = existsSync(OUT_PATH) ? readFileSync(OUT_PATH, 'utf8') : '';

/** filename → hand-written annotation, harvested from the previous doc. */
const annotations = {};
for (const m of prev.matchAll(/^- `([^`]+\.svg)`[^—\n]*(?:—\s*(.+))?$/gm)) {
  const [, file, note] = m;
  if (!file.startsWith('{') && note?.trim()) annotations[file] = note.trim();
}

const naming = prev.match(/## Naming Convention\n(?:- .*\n)+/)?.[0].trimEnd() ?? FALLBACK_NAMING;

// ── Classify ─────────────────────────────────────────────────────────────────

const isFlag        = f => f.endsWith('-wrc.svg');
const isPlaceholder = f => f === 'tbc.svg' || f === 'tbd.svg';

/** filename → owning track slug */
const browserOf = {};
const calendarOf = {};
for (const t of tracks) {
  if (t.browserSvg) browserOf[t.browserSvg] ??= t.slug;
  for (const s of t.calendarSvgs ?? []) calendarOf[s] ??= t.slug;
  for (const l of t.layouts ?? []) {
    for (const s of l.calendarSvgs ?? []) calendarOf[s] ??= t.slug;
  }
}

const flags        = disk.filter(isFlag);
const placeholders = disk.filter(isPlaceholder);
const circuits     = disk.filter(f => !isFlag(f) && !isPlaceholder(f));
const browserMapped = circuits.filter(f => f in browserOf);
const calendarOnly  = circuits.filter(f => !(f in browserOf));
const unreferenced  = circuits.filter(f => !(f in browserOf) && !(f in calendarOf));

const missingBrowser = tracks
  .filter(t => !t.browserSvg || !disk.includes(t.browserSvg))
  .map(t => t.slug);
const missingCalendar = Object.keys(calendarOf).filter(f => !disk.includes(f)).sort();

// ── Render ───────────────────────────────────────────────────────────────────

const entry = (file, owners) => {
  const slug = owners[file];
  const note = annotations[file];
  return `- \`${file}\`${slug ? ` (${slug})` : ''}${note ? ` — ${note}` : ''}`;
};

const today = new Date().toISOString().slice(0, 10);

const md = [
  '# Track Map Status',
  `_Last updated: ${today} — generated by \`npm run gen:map-status\`, do not edit counts by hand._`,
  '',
  '## Summary',
  '| | Count |',
  '|---|---|',
  `| Files on disk | **${disk.length}** |`,
  `| Circuit SVGs (all layouts) | **${circuits.length}** |`,
  `| — of which set as a \`browserSvg\` | **${browserMapped.length}** |`,
  `| — \`calendarSvg\`-only (no browser entry) | **${calendarOnly.length}** |`,
  `| WRC / ERC flags | **${flags.length}** |`,
  `| Placeholder infographics | **${placeholders.length}** |`,
  `| Missing \`browserSvg\`s | **${missingBrowser.length}** |`,
  `| Missing calendar refs (not yet drawn) | **${missingCalendar.length}** |`,
  `| Unreferenced files | **${unreferenced.length}** |`,
  '',
  `Derived from \`public/assets/track-maps/\` and \`data/tracks.json\`: ` +
    `${browserMapped.length} + ${calendarOnly.length} + ${flags.length} + ${placeholders.length} = ${disk.length}.`,
  '',
  naming,
  '',
  `## Circuit SVGs — browser-mapped (${browserMapped.length})`,
  'One per track: the layout shown in the track browser grid and the detail-page hero.',
  ...browserMapped.map(f => entry(f, browserOf)),
  '',
  `## calendarSvg-only (${calendarOnly.length})`,
  'Series-specific layouts referenced from the calendar; no standalone browser entry.',
  ...calendarOnly.map(f => entry(f, calendarOf)),
  '',
  `## WRC / ERC Flags (${flags.length})`,
  ...flags.map(f => entry(f, {})),
  '',
  `## Placeholder Infographics (${placeholders.length})`,
  ...placeholders.map(f => entry(f, {})),
  '',
  '## Still Missing',
  missingCalendar.length
    ? missingCalendar.map(f => `- \`${f}\` — referenced by the calendar, not yet drawn`).join('\n')
    : '- Calendar refs not yet drawn: **none**',
  missingBrowser.length
    ? missingBrowser.map(s => `- ${s} — no \`browserSvg\` set`).join('\n')
    : '- Tracks without a `browserSvg`: **none**',
  unreferenced.length
    ? unreferenced.map(f => `- \`${f}\` — on disk but referenced by nothing`).join('\n')
    : '- Unreferenced files: **none**',
  '',
].join('\n');

// ── Output ───────────────────────────────────────────────────────────────────

if (CHECK_ONLY) {
  // Ignore the generated date line so a stale-date-only diff isn't a failure.
  const strip = s => s.replace(/^_Last updated:.*$/m, '');
  if (strip(prev) !== strip(md)) {
    console.error('\n❌  track-map-status.md is out of date — run: npm run gen:map-status\n');
    process.exit(1);
  }
  console.log('✓ track-map-status.md is up to date');
  process.exit(0);
}

writeFileSync(OUT_PATH, md, 'utf8');

const warn = [];
if (missingBrowser.length)  warn.push(`${missingBrowser.length} track(s) with no browserSvg`);
if (missingCalendar.length) warn.push(`${missingCalendar.length} calendar ref(s) not drawn`);
if (unreferenced.length)    warn.push(`${unreferenced.length} unreferenced file(s)`);

console.log(
  `✓ track-map-status.md generated — ${disk.length} files ` +
  `(${browserMapped.length} browser-mapped, ${calendarOnly.length} calendarSvg-only, ` +
  `${flags.length} flags, ${placeholders.length} placeholders)`
);
console.log(`  ${Object.keys(annotations).length} annotation(s) carried over`);
if (warn.length) console.log(`  ⚠️  ${warn.join(' · ')}`);
